import assert from 'node:assert/strict';
import { LocalStorageTaskAdapter } from '../src/features/tasks/storage/LocalStorageTaskAdapter.js';
import { ApiTaskAdapter } from '../src/features/tasks/storage/ApiTaskAdapter.js';
import { taskStorageKey } from '../src/features/tasks/storage/TaskStorageAdapter.js';
import { hasEmployeeWork } from '../src/features/tasks/employee-policy.js';
const records = new Map();
const storage = { getItem: key => records.get(key) ?? null, setItem: (key, contents) => records.set(key, contents) };
const designer = { id: 'one', name: 'First employee', activeRole: 'creative-communication-associate' };
const first = new LocalStorageTaskAdapter(designer, storage);
const second = new LocalStorageTaskAdapter({ id: 'two', name: 'Other employee', activeRole: 'it-system-analyst' }, storage);
const initial = await first.load();
assert.ok(initial.tasks.length > 0);
assert.ok(initial.tasks.every(task => task.ownerId === designer.id));
const stale = structuredClone(initial);
initial.tasks[0].brief = 'Changed brief';
const saved = await first.save(initial);
assert.equal((await first.load()).tasks[0].brief, 'Changed brief');
assert.equal((await second.getTasks()).length, 0);
await assert.rejects(() => first.save(stale), /another tab/);
await assert.rejects(() => second.save(saved), /another employee/);
await assert.rejects(() => first.updateTaskStatus(initial.tasks[0].id, 'Completed'), /reviewer/);
await assert.rejects(() => new ApiTaskAdapter().getTasks(), /not configured/);
const legacy = structuredClone(initial);
legacy.employee = { id: '99', name: 'Legacy employee' };
legacy.tasks.forEach(task => { task.ownerId = '99'; });
records.set(`${taskStorageKey}:99`, JSON.stringify(legacy));
const migrated = await new LocalStorageTaskAdapter({ id: 99, name: 'Legacy employee', activeRole: 'creative-communication-associate' }, storage).load();
assert.equal(migrated.tasks[0].ownerId, 99);
assert.ok(records.has(`${taskStorageKey}:99`));
for (const role of ['chairman', 'admin', 'super-admin']) assert.equal(hasEmployeeWork(role), false);
records.set(taskStorageKey, '{broken');
await assert.rejects(() => first.load(), SyntaxError);
assert.equal(records.get(taskStorageKey), '{broken');
console.log('PASS: account-scoped persistence, stale writes, approval guard, empty noncreative queue and corrupt-record preservation.');
