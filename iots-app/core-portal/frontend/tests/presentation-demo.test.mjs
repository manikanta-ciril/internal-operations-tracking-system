import assert from 'node:assert/strict';
import { LocalStorageTaskAdapter } from '../src/features/tasks/storage/LocalStorageTaskAdapter.js';
import { dailyReport } from '../src/features/daily-report/reportEngine.js';
import { isPresentationEmployee } from '../src/features/tasks/storage/presentation-demo.js';
const saved = new Map();
const storage = { getItem: key => saved.get(key) ?? null, setItem: (key, value) => saved.set(key, value) };
const employee = { id: 'presentation-test', name: 'Sai Deepthi', username: 'deepthi', activeRole: 'creative-communication-associate' };
const adapter = new LocalStorageTaskAdapter(employee, storage);
const demo = await adapter.load();
assert.ok([...saved.keys()].some(key => key.includes('presentation-backup')));
assert.ok(new Set(demo.tasks.map(task => task.status)).size >= 5);
const report = dailyReport(demo);
assert.ok(report.completed.length > 0);
assert.ok(report.progress.length > 0);
assert.ok(report.pending.length > 0);
const revision = demo.storageRevision;
assert.equal((await adapter.load()).storageRevision, revision, 'Do not reset again on reload');
assert.equal(isPresentationEmployee({ ...employee, name: 'Other person', username: 'other' }), false);
console.log('PASS: backed-up Deepthi-only demo, diverse stages, daily report groups and one-time setup.');
